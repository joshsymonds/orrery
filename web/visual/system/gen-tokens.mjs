// Writes tokens.css from tokens.json, beside this file.
//   node gen-tokens.mjs          write tokens.css
//   node gen-tokens.mjs --check  exit 1 when tokens.css is not what tokens.json generates
// Every wireframe stylesheet reads only the variables this writes; lint-css.mjs holds them to that.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(fs.readFileSync(path.join(here, 'tokens.json'), 'utf8'));

const at = (ref) => ref.split('.').reduce((node, key) => {
  if (node === undefined || node[key] === undefined) throw new Error(`tokens.json: {${ref}} names nothing`);
  return node[key];
}, tokens);
// A value that is "{a.b}" resolves to what a.b holds, through as many steps as it takes.
const resolve = (value) => {
  const ref = typeof value === 'string' && /^\{([^}]+)\}$/.exec(value);
  return ref ? resolve(at(ref[1])) : value;
};
// A reference to another token is written as that token's variable, so the sheet keeps the chain.
const cssRef = (value) => {
  const ref = typeof value === 'string' && /^\{([^}]+)\}$/.exec(value);
  return ref ? `var(--o-${ref[1].replace(/\./g, '-')})` : value;
};
const dash = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const pct = (alpha) => `${Math.round(resolve(alpha) * 100)}%`;
const bezier = (points) => `cubic-bezier(${resolve(points).join(', ')})`;

const out = [];
const put = (name, value) => out.push(`  --o-${dash(name)}: ${value};`);
const group = (title) => out.push('', `  /* ${title} */`);

group('palette: Catppuccin Mocha. Components never name these; they name a role.');
for (const [name, hex] of Object.entries(tokens.palette)) put(`palette-${name}`, hex);

for (const name of ['surface', 'line', 'ink']) {
  group(name);
  for (const [key, value] of Object.entries(tokens[name])) put(`${name}-${key}`, cssRef(value));
}

// A tint is its colour at alpha.tintFill over whatever is under it, outlined at alpha.tintLine.
const tinted = (name, title) => {
  group(title);
  for (const [key, value] of Object.entries(tokens[name])) {
    put(`${name}-${key}`, cssRef(value));
    put(`${name}-${key}-fill`, `color-mix(in srgb, var(--o-${name}-${dash(key)}) ${pct(tokens.alpha.tintFill)}, transparent)`);
    put(`${name}-${key}-line`, `color-mix(in srgb, var(--o-${name}-${dash(key)}) ${pct(tokens.alpha.tintLine)}, transparent)`);
  }
};
tinted('role', 'role: what a colour means. -fill and -line are its tint and the tint\'s outline.');
tinted('series', 'series: tells things apart from each other and means nothing else');
// A state, a tone and a level are drawn solid: a glyph, a rail, a cell, a bar. Only a role is ever a tint.
for (const [name, title] of [['state', 'state: a session or a step'], ['tone', 'tone: a task\'s cell on an epic'], ['level', 'level: a quantity (a host stat, the context)'], ['prose', 'prose: Markdown in a reply'], ['syntax', 'syntax: code in a code block']]) {
  group(title);
  for (const [key, value] of Object.entries(tokens[name])) put(`${name}-${key}`, cssRef(value));
}

group('type: one font shorthand per level, and the label\'s tracking');
put('font-mono', tokens.font.mono);
for (const [name, weight] of Object.entries(tokens.font.weight)) put(`font-weight-${name}`, weight);
for (const [name, t] of Object.entries(tokens.type)) {
  put(`type-${name}`, `${resolve(t.weight)} ${t.size}px/${t.line}px var(--o-font-mono)`);
  put(`type-${name}-size`, `${t.size}px`);
  put(`type-${name}-line`, `${t.line}px`);
  if (t.tracking) put(`type-${name}-tracking`, `${t.tracking}em`);
}

for (const name of ['space', 'radius', 'size']) {
  group(name);
  for (const [key, value] of Object.entries(tokens[name])) put(`${name}-${key}`, `${value}px`);
}

group('layout');
for (const [key, value] of Object.entries(tokens.layout)) put(`layout-${key}`, key.endsWith('Ch') ? `${value}ch` : `${value}px`);

group('elevation');
for (const [name, e] of Object.entries(tokens.elevation)) {
  put(`elevation-${name}`, `${e.x}px ${e.y}px ${e.blur}px color-mix(in srgb, ${resolve(e.color)} ${pct(e.alpha)}, transparent)`);
}
put('scrim', `color-mix(in srgb, var(--o-palette-crust) ${pct(tokens.alpha.scrim)}, transparent)`);

group('layers, low to high');
for (const [name, z] of Object.entries(tokens.z)) put(`z-${name}`, z);

group('motion');
for (const [name, m] of Object.entries(tokens.motion.move)) put(`move-${name}`, `${m.ms}ms ${bezier(m.ease)}`);
for (const [name, l] of Object.entries(tokens.motion.loop)) put(`loop-${name}`, `${l.ms}ms`);
put('pulse-low', tokens.motion.loop.pulse.to);
put('distance-drill', `${tokens.motion.distance.drill}px`);

const reduced = tokens.motion.reduced.ms;
const css = [
  '/* Generated by gen-tokens.mjs from tokens.json. Do not edit: change tokens.json and run the generator. */',
  ':root {' + out.join('\n'),
  '}',
  '',
  `/* ${tokens.motion.reduced.note} */`,
  '@media (prefers-reduced-motion: reduce) {',
  '  :root {',
  ...Object.keys(tokens.motion.move).map((name) => `    --o-move-${name}: ${reduced}ms linear;`),
  '  }',
  '}',
  '',
].join('\n');

const target = path.join(here, 'tokens.css');
if (process.argv.includes('--check')) {
  const have = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (have !== css) { console.error('tokens.css is stale: run node gen-tokens.mjs'); process.exit(1); }
  console.log('tokens.css matches tokens.json');
} else {
  fs.writeFileSync(target, css);
  console.log(`wrote ${path.relative(process.cwd(), target)}: ${out.filter((l) => l.includes('--o-')).length} variables`);
}
