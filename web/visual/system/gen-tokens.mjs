// Writes the design tokens from tokens.json: one run writes four files, and --check writes none.
//   node gen-tokens.mjs                 write all four
//   node gen-tokens.mjs --check         exit 1, naming each output that differs or is missing
//   node gen-tokens.mjs --root <dir>    read <dir>/web/visual/system/tokens.json; write or check the four under <dir>
// The four: tokens.css beside this file, which every wireframe stylesheet reads (lint-css.mjs holds them to the
// variables it defines); web/src/tokens.css, the same variables for the web app; web/src/tokens/rules.ts; and the
// Android OrreryTokens.kt.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const rootAt = argv.indexOf('--root');
if (rootAt !== -1 && argv[rootAt + 1] === undefined) {
  console.error('gen-tokens.mjs: --root takes a directory');
  process.exit(2);
}
const root = rootAt === -1 ? path.resolve(here, '../../..') : path.resolve(argv[rootAt + 1]);
const tokens = JSON.parse(fs.readFileSync(path.join(root, 'web/visual/system/tokens.json'), 'utf8'));

const at = (ref) => ref.split('.').reduce((node, key) => {
  if (node === undefined || node[key] === undefined) throw new Error(`tokens.json: {${ref}} names nothing`);
  return node[key];
}, tokens);
// A value that is "{a.b}" resolves to what a.b holds, through as many steps as it takes.
const resolve = (value) => {
  const ref = typeof value === 'string' && /^\{([^}]+)\}$/.exec(value);
  return ref ? resolve(at(ref[1])) : value;
};
// A reference to another token is written as that token's variable, so the sheet keeps the chain.
const cssRef = (value) => {
  const ref = typeof value === 'string' && /^\{([^}]+)\}$/.exec(value);
  return ref ? `var(--o-${ref[1].replace(/\./g, '-')})` : value;
};
const dash = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const pct = (alpha) => `${Math.round(resolve(alpha) * 100)}%`;
const bezier = (points) => `cubic-bezier(${resolve(points).join(', ')})`;

const NOTE = 'Generated by web/visual/system/gen-tokens.mjs from tokens.json. Not edited by hand: change tokens.json and run `just tokens`.';
const SYSTEM_HEAD = '/* Generated by gen-tokens.mjs from tokens.json. Do not edit: change tokens.json and run the generator. */';

function cssText(head) {
  const out = [];
  const put = (name, value) => out.push(`  --o-${dash(name)}: ${value};`);
  const group = (title) => out.push('', `  /* ${title} */`);

  group('palette: Catppuccin Mocha. Components never name these; they name a role.');
  for (const [name, hex] of Object.entries(tokens.palette)) put(`palette-${name}`, hex);

  for (const name of ['surface', 'line', 'ink']) {
    group(name);
    for (const [key, value] of Object.entries(tokens[name])) put(`${name}-${key}`, cssRef(value));
  }

  // A tint is its colour at alpha.tintFill over whatever is under it, outlined at alpha.tintLine.
  const tinted = (name, title) => {
    group(title);
    for (const [key, value] of Object.entries(tokens[name])) {
      put(`${name}-${key}`, cssRef(value));
      put(`${name}-${key}-fill`, `color-mix(in srgb, var(--o-${name}-${dash(key)}) ${pct(tokens.alpha.tintFill)}, transparent)`);
      put(`${name}-${key}-line`, `color-mix(in srgb, var(--o-${name}-${dash(key)}) ${pct(tokens.alpha.tintLine)}, transparent)`);
    }
  };
  tinted('role', 'role: what a colour means. -fill and -line are its tint and the tint\'s outline.');
  tinted('series', 'series: tells things apart from each other and means nothing else');
  // A state, a tone and a level are drawn solid: a glyph, a rail, a cell, a bar. Only a role is ever a tint.
  for (const [name, title] of [['state', 'state: a session or a step'], ['tone', 'tone: a task\'s cell on an epic'], ['level', 'level: a quantity (a host stat, the context)'], ['prose', 'prose: Markdown in a reply'], ['syntax', 'syntax: code in a code block']]) {
    group(title);
    for (const [key, value] of Object.entries(tokens[name])) put(`${name}-${key}`, cssRef(value));
  }

  group('type: one font shorthand per level, and the label\'s tracking');
  put('font-mono', tokens.font.mono);
  for (const [name, weight] of Object.entries(tokens.font.weight)) put(`font-weight-${name}`, weight);
  for (const [name, t] of Object.entries(tokens.type)) {
    put(`type-${name}`, `${resolve(t.weight)} ${t.size}px/${t.line}px var(--o-font-mono)`);
    put(`type-${name}-size`, `${t.size}px`);
    put(`type-${name}-line`, `${t.line}px`);
    if (t.tracking) put(`type-${name}-tracking`, `${t.tracking}em`);
  }

  for (const name of ['space', 'radius', 'size']) {
    group(name);
    for (const [key, value] of Object.entries(tokens[name])) put(`${name}-${key}`, `${value}px`);
  }

  group('layout');
  for (const [key, value] of Object.entries(tokens.layout)) put(`layout-${key}`, key.endsWith('Ch') ? `${value}ch` : `${value}px`);

  group('elevation');
  for (const [name, e] of Object.entries(tokens.elevation)) {
    put(`elevation-${name}`, `${e.x}px ${e.y}px ${e.blur}px color-mix(in srgb, ${resolve(e.color)} ${pct(e.alpha)}, transparent)`);
  }
  put('scrim', `color-mix(in srgb, var(--o-palette-crust) ${pct(tokens.alpha.scrim)}, transparent)`);

  group('layers, low to high');
  for (const [name, z] of Object.entries(tokens.z)) put(`z-${name}`, z);

  group('motion');
  for (const [name, m] of Object.entries(tokens.motion.move)) put(`move-${name}`, `${m.ms}ms ${bezier(m.ease)}`);
  for (const [name, l] of Object.entries(tokens.motion.loop)) put(`loop-${name}`, `${l.ms}ms`);
  put('pulse-low', tokens.motion.loop.pulse.to);
  put('distance-drill', `${tokens.motion.distance.drill}px`);

  const reduced = tokens.motion.reduced.ms;
  return [
    head,
    ':root {' + out.join('\n'),
    '}',
    '',
    `/* ${tokens.motion.reduced.note} */`,
    '@media (prefers-reduced-motion: reduce) {',
    '  :root {',
    ...Object.keys(tokens.motion.move).map((name) => `    --o-move-${name}: ${reduced}ms linear;`),
    '  }',
    '}',
    '',
  ].join('\n');
}

// Kotlin: one object per top-level group and one val per token. A digit key is spelled as an English word, and a hard
// keyword is backticked.
const KOTLIN_KEYWORDS = new Set(['as', 'break', 'class', 'continue', 'do', 'else', 'false', 'for', 'fun', 'if', 'in', 'interface', 'is', 'null', 'object', 'package', 'return', 'super', 'this', 'throw', 'true', 'try', 'typealias', 'typeof', 'val', 'var', 'when', 'while']);
const ONES = ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten', 'eleven', 'twelve', 'thirteen', 'fourteen', 'fifteen', 'sixteen', 'seventeen', 'eighteen', 'nineteen'];
const TENS = ['', '', 'twenty', 'thirty', 'forty', 'fifty', 'sixty', 'seventy', 'eighty', 'ninety'];
const cap = (s) => s[0].toUpperCase() + s.slice(1);
// 1 is one, 24 is twentyFour.
const word = (key) => {
  if (!/^\d+$/.test(key)) return key;
  const n = Number(key);
  if (n >= 100) throw new Error(`tokens.json: ${key} has no Kotlin name`);
  if (n < 20) return ONES[n];
  return n % 10 === 0 ? TENS[n / 10] : `${TENS[Math.floor(n / 10)]}${cap(ONES[n % 10])}`;
};
const name = (key) => {
  const w = word(key);
  return KOTLIN_KEYWORDS.has(w) ? '`' + w + '`' : w;
};
const colour = (value) => {
  const hex = resolve(value);
  if (!/^#[0-9a-fA-F]{6}$/.test(hex)) throw new Error(`tokens.json: ${value} is not a #rrggbb colour`);
  return `Color(0xFF${hex.slice(1).toUpperCase()})`;
};
const float = (n) => `${n}f`;
const dp = (n) => (n < 0 ? `(${n}).dp` : `${n}.dp`);
const block = (head, members) => [`${head} {`, ...members.map((line) => (line === '' ? line : `    ${line}`)), '}'];
const siblings = (blocks) => blocks.flatMap((b, i) => (i === 0 ? b : ['', ...b]));
const note = (text) => `// ${text}`;
const refName = (ref) => ref.slice(1, -1).split('.').at(-1);
const weightRef = (ref) => {
  if (!/^\{font\.weight\.\w+\}$/.test(ref)) throw new Error(`tokens.json: a type's weight must name a font.weight, got ${ref}`);
  return `Font.Weight.${refName(ref)}`;
};
const easeRef = (ref) => {
  if (!/^\{motion\.ease\.\w+\}$/.test(ref)) throw new Error(`tokens.json: a move's ease must name a motion.ease, got ${ref}`);
  return `Ease.${name(refName(ref))}`;
};

function kotlinText() {
  const colours = (node) => Object.entries(node).map(([k, v]) => `val ${name(k)}: Color = ${colour(v)}`);
  // A role or a series colour, with its tint and its outline: the colour at the alpha its token names.
  const tinted = (node) => Object.entries(node).flatMap(([k, v]) => [
    `val ${name(k)}: Color = ${colour(v)}`,
    `val ${word(k)}Fill: Color = ${name(k)}.copy(alpha = Alpha.tintFill)`,
    `val ${word(k)}Line: Color = ${name(k)}.copy(alpha = Alpha.tintLine)`,
  ]);
  const lengths = (node) => Object.entries(node).map(([k, v]) => `val ${name(k)}: Dp = ${dp(v)}`);
  const floats = (node) => Object.entries(node).map(([k, v]) => `val ${name(k)}: Float = ${float(v)}`);
  const c = tokens.rule.context;
  const m = tokens.motion;
  const layout = Object.entries(tokens.layout).map(([k, v]) => (k.endsWith('Ch') ? `val ${name(k)}: Int = ${v}` : `val ${name(k)}: Dp = ${dp(v)}`));
  const elevation = Object.entries(tokens.elevation).map(([k, e]) => block(`object ${cap(k)}`, [
    `val x: Dp = ${dp(e.x)}`,
    `val y: Dp = ${dp(e.y)}`,
    `val blur: Dp = ${dp(e.blur)}`,
    `val color: Color = ${colour(e.color)}`,
    `val alpha: Float = ${float(resolve(e.alpha))}`,
  ]));
  const typeBody = Object.entries(tokens.type).flatMap(([k, t]) => [
    `val ${name(k)}: TextStyle = TextStyle(fontFamily = OrreryMono, fontWeight = ${weightRef(t.weight)}, fontSize = ${t.size}.sp, lineHeight = ${t.line}.sp, letterSpacing = ${float(t.tracking)}.em)`,
    `const val ${name(k)}Caps: Boolean = ${t.caps}`,
  ]);
  const ease = Object.entries(m.ease).map(([k, pts]) => `val ${name(k)}: Easing = CubicBezierEasing(${pts.map(float).join(', ')})`);
  const move = Object.entries(m.move).map(([k, mv]) => `val ${name(k)}: Timing = Timing(${mv.ms}, ${easeRef(mv.ease)})`);
  const loop = Object.entries(m.loop).flatMap(([k, l]) => [
    `val ${name(k)}: Int = ${l.ms}`,
    ...Object.entries(l).filter(([f]) => f !== 'ms').map(([f, v]) => `val ${name(k)}${cap(f)}: Float = ${float(v)}`),
  ]);

  const top = block('object OrreryTokens', siblings([
    block('object Palette', colours(tokens.palette)),
    block('object Surface', colours(tokens.surface)),
    block('object Line', colours(tokens.line)),
    block('object Ink', colours(tokens.ink)),
    block('object Role', tinted(tokens.role)),
    block('object State', colours(tokens.state)),
    block('object Tone', colours(tokens.tone)),
    block('object Level', colours(tokens.level)),
    block('object Series', tinted(tokens.series)),
    block('object Prose', colours(tokens.prose)),
    block('object Syntax', colours(tokens.syntax)),
    block('object Rule', [
      note(`rule.series: ${tokens.rule.series.note}`),
      note(`rule.level: ${tokens.rule.level.note}`),
      note(`rule.context: ${c.note}`),
      ...block('object Context', [
        `val limits: List<Int> = listOf(${c.limits.join(', ')})`,
        `val blocks: Int = ${c.blocks}`,
        `val percentPerBlock: Int = ${c.percentPerBlock}`,
      ]),
    ]),
    block('object Alpha', floats(tokens.alpha)),
    block('object Font', [
      `val mono: String = ${JSON.stringify(tokens.font.mono)}`,
      ...block('object Weight', Object.entries(tokens.font.weight).map(([k, v]) => `val ${name(k)}: FontWeight = FontWeight(${v})`)),
    ]),
    block('object Type', typeBody),
    block('object Space', lengths(tokens.space)),
    block('object Radius', lengths(tokens.radius)),
    block('object Size', lengths(tokens.size)),
    block('object Layout', layout),
    block('object Elevation', siblings(elevation)),
    block('object Z', floats(tokens.z)),
    block('object Motion', siblings([
      ['class Timing(val millis: Int, val easing: Easing)'],
      block('object Ease', ease),
      block('object Move', move),
      block('object Loop', loop),
      block('object Reduced', [note(`motion.reduced: ${m.reduced.note}`), `val millis: Int = ${m.reduced.ms}`]),
      block('object Distance', lengths(m.distance)),
    ])),
  ]));

  return [
    `// ${NOTE}`,
    'package io.github.joshsymonds.orrery.ui.theme',
    '',
    'import androidx.compose.animation.core.CubicBezierEasing',
    'import androidx.compose.animation.core.Easing',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.text.TextStyle',
    'import androidx.compose.ui.text.font.FontWeight',
    'import androidx.compose.ui.unit.Dp',
    'import androidx.compose.ui.unit.dp',
    'import androidx.compose.ui.unit.em',
    'import androidx.compose.ui.unit.sp',
    '',
    ...top,
    '',
  ].join('\n');
}

// rules.ts: the rule's context as plain values, typed as const. The notes of the series and the level say what the
// colours mean, so they are written beside it.
function rulesText() {
  const c = tokens.rule.context;
  return [
    `// ${NOTE}`,
    `// rule.series: ${tokens.rule.series.note}`,
    `// rule.level: ${tokens.rule.level.note}`,
    `// rule.context: ${c.note}`,
    'export const context = {',
    `  limits: [${c.limits.join(', ')}],`,
    `  blocks: ${c.blocks},`,
    `  percentPerBlock: ${c.percentPerBlock},`,
    '} as const;',
    '',
  ].join('\n');
}

const outputs = [
  ['web/visual/system/tokens.css', cssText(SYSTEM_HEAD)],
  ['web/src/tokens.css', cssText(`/* ${NOTE} */`)],
  ['web/src/tokens/rules.ts', rulesText()],
  ['android/app/src/main/kotlin/io/github/joshsymonds/orrery/ui/theme/OrreryTokens.kt', kotlinText()],
];

const matches = (file, text) => fs.existsSync(file) && fs.readFileSync(file, 'utf8') === text;

if (argv.includes('--check')) {
  const stale = outputs.filter(([rel, text]) => !matches(path.join(root, rel), text));
  for (const [rel] of stale) console.error(`${rel} differs from tokens.json or is missing`);
  if (stale.length) {
    console.error('run just tokens to write them');
    process.exitCode = 1;
  } else {
    console.log('the four token outputs match tokens.json');
  }
} else {
  for (const [rel, text] of outputs) {
    const target = path.join(root, rel);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, text);
    console.log(`wrote ${rel}`);
  }
}
