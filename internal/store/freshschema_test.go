// writeFreshSchemaEnv names the environment variable that makes TestStoreFreshSchemaMatchesMigrations write schema.sql
// from the migrations, as `just generate` runs it, in place of checking it.
const writeFreshSchemaEnv = "ORRERY_WRITE_FRESH_SCHEMA"

// freshSchemaHeader opens schema.sql.
const freshSchemaHeader = "-- Code generated by `just generate` from internal/store/migrations. DO NOT EDIT.\n" +
	"-- The database the migrations make from an empty file; Open makes an empty database from it.\n"

// gooseTable is the table goose records the applied migrations in.
const gooseTable = "goose_db_version"

// TestStoreFreshSchemaMatchesMigrations checks that freshSchema is the database the embedded migrations make: a store
// opened empty through the migrations, one at a time, and a store opened empty from freshSchema hold the same schema
// objects, in the same order, and the same rows in every table, goose's record of the migrations included but for
// when each was applied. With ORRERY_WRITE_FRESH_SCHEMA=1 it writes schema.sql from the migrations instead.
func TestStoreFreshSchemaMatchesMigrations(t *testing.T) {
	ctx := t.Context()
	migrated, err := Open(ctx, filepath.Join(t.TempDir(), "migrated.db"), withMigrationsOnly())
	if err != nil {
		t.Fatalf("open through the migrations: %v", err)
	}
	t.Cleanup(func() { _ = migrated.Close() })

	if os.Getenv(writeFreshSchemaEnv) == "1" {
		if err = os.WriteFile("schema.sql", []byte(dumpFreshSchema(t, migrated.db.DB)), 0o644); err != nil {
			t.Fatalf("write schema.sql: %v", err)
		}
		return
	}

	fresh, err := Open(ctx, filepath.Join(t.TempDir(), "fresh.db"))
	if err != nil {
		t.Fatalf("open from freshSchema: %v", err)
	}
	t.Cleanup(func() { _ = fresh.Close() })

	want, got := describeDatabase(t, migrated.db.DB), describeDatabase(t, fresh.db.DB)
	if !slices.Equal(want, got) {
		t.Fatalf("a store made from schema.sql differs from one the migrations make; run `just generate`.\n"+
			"migrations:\n%s\nschema.sql:\n%s", strings.Join(want, "\n"), strings.Join(got, "\n"))
	}
}

// TestStoreOpenMakesAnEmptyDatabaseFromFreshSchemaOnly checks that Open makes only an empty database from freshSchema:
// a database that already holds a schema object keeps it, and is migrated as before.
func TestStoreOpenMakesAnEmptyDatabaseFromFreshSchemaOnly(t *testing.T) {
	ctx := t.Context()
	path := filepath.Join(t.TempDir(), "kept.db")
	seed, err := sql.Open("sqlite3", "file:"+path)
	if err != nil {
		t.Fatalf("open seed database: %v", err)
	}
	if _, err = seed.ExecContext(ctx, "CREATE TABLE kept (x INTEGER)"); err != nil {
		t.Fatalf("seed a table: %v", err)
	}
	if err = seed.Close(); err != nil {
		t.Fatalf("close seed database: %v", err)
	}

	s, err := Open(ctx, path)
	if err != nil {
		t.Fatalf("Open of a database with a table: %v", err)
	}
	t.Cleanup(func() { _ = s.Close() })
	var kept int
	if err = s.db.DB.QueryRowContext(ctx,
		"SELECT count(*) FROM sqlite_master WHERE type = 'table' AND name = 'kept'").Scan(&kept); err != nil {
		t.Fatalf("read the seeded table: %v", err)
	}
	if kept != 1 {
		t.Fatal("Open dropped the table the database held, want it kept")
	}
}

// dumpFreshSchema returns schema.sql's text for db, a database the migrations made from an empty file: each schema
// object's SQL in the order sqlite_master holds it, the rows of each table, and goose's record of each migration, with
// its tstamp left to the column's default.
func dumpFreshSchema(t *testing.T, db *sql.DB) string {
	t.Helper()
	var b strings.Builder
	b.WriteString(freshSchemaHeader)
	for _, object := range schemaObjects(t, db) {
		if object.sql == "" || strings.HasPrefix(object.name, "sqlite_") {
			continue
		}
		b.WriteString(object.sql + ";\n")
	}
	for _, table := range freshTableNames(t, db) {
		for _, row := range tableRows(t, db, table) {
			b.WriteString(row + ";\n")
		}
	}
	return b.String()
}

// schemaObject is one row of sqlite_master, without its root page.
type schemaObject struct {
	typ, name, table, sql string
}

// schemaObjects returns db's sqlite_master rows in rowid order.
func schemaObjects(t *testing.T, db *sql.DB) []schemaObject {
	t.Helper()
	rows, err := db.QueryContext(context.Background(),
		"SELECT type, name, tbl_name, coalesce(sql, '') FROM sqlite_master ORDER BY rowid")
	if err != nil {
		t.Fatalf("read sqlite_master: %v", err)
	}
	defer func() { _ = rows.Close() }()
	var objects []schemaObject
	for rows.Next() {
		var o schemaObject
		if err = rows.Scan(&o.typ, &o.name, &o.table, &o.sql); err != nil {
			t.Fatalf("scan sqlite_master: %v", err)
		}
		objects = append(objects, o)
	}
	if err = rows.Err(); err != nil {
		t.Fatalf("read sqlite_master: %v", err)
	}
	return objects
}

// freshTableNames returns the names of db's tables, sqlite's own included, in sqlite_master's order.
func freshTableNames(t *testing.T, db *sql.DB) []string {
	t.Helper()
	var names []string
	for _, o := range schemaObjects(t, db) {
		if o.typ == "table" && o.name != "sqlite_sequence" {
			names = append(names, o.name)
		}
	}
	return names
}

// freshTableColumns returns the names of table's columns in their order. goose's table leaves out tstamp, which records when
// each migration was applied.
func freshTableColumns(t *testing.T, db *sql.DB, table string) []string {
	t.Helper()
	rows, err := db.QueryContext(context.Background(), "SELECT name FROM pragma_table_info(?) ORDER BY cid", table)
	if err != nil {
		t.Fatalf("read the columns of %s: %v", table, err)
	}
	defer func() { _ = rows.Close() }()
	var columns []string
	for rows.Next() {
		var name string
		if err = rows.Scan(&name); err != nil {
			t.Fatalf("scan a column of %s: %v", table, err)
		}
		if table == gooseTable && name == "tstamp" {
			continue
		}
		columns = append(columns, name)
	}
	if err = rows.Err(); err != nil {
		t.Fatalf("read the columns of %s: %v", table, err)
	}
	return columns
}

// tableRows returns each row of table as an INSERT statement of the columns freshTableColumns gives, with its values quoted
// by SQLite, ordered by that text, since a WITHOUT ROWID table has no rowid to order by.
func tableRows(t *testing.T, db *sql.DB, table string) []string {
	t.Helper()
	ctx := context.Background()
	columns := freshTableColumns(t, db, table)
	quoted := make([]string, len(columns))
	names := make([]string, len(columns))
	for i, c := range columns {
		quoted[i] = fmt.Sprintf("quote(%q)", c)
		names[i] = fmt.Sprintf("%q", c)
	}
	query := fmt.Sprintf("SELECT %s FROM %q ORDER BY 1", strings.Join(quoted, " || ',' || "), table)
	rows, err := db.QueryContext(ctx, query)
	if err != nil {
		t.Fatalf("read the rows of %s: %v", table, err)
	}
	defer func() { _ = rows.Close() }()
	var inserts []string
	for rows.Next() {
		var values string
		if err = rows.Scan(&values); err != nil {
			t.Fatalf("scan a row of %s: %v", table, err)
		}
		inserts = append(inserts,
			fmt.Sprintf("INSERT INTO %q (%s) VALUES (%s)", table, strings.Join(names, ", "), values))
	}
	if err = rows.Err(); err != nil {
		t.Fatalf("read the rows of %s: %v", table, err)
	}
	return inserts
}

// describeDatabase returns what the fresh-schema check compares of db: each sqlite_master row but its root page, in
// rowid order, then each table's rows as tableRows gives them, and sqlite_sequence's.
func describeDatabase(t *testing.T, db *sql.DB) []string {
	t.Helper()
	objects := schemaObjects(t, db)
	lines := make([]string, 0, len(objects))
	for _, o := range objects {
		lines = append(lines, fmt.Sprintf("%s %s on %s: %s", o.typ, o.name, o.table, o.sql))
	}
	for _, table := range append(freshTableNames(t, db), "sqlite_sequence") {
		lines = append(lines, tableRows(t, db, table)...)
	}
	return lines
}
