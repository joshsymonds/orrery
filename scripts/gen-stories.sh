#!/usr/bin/env bash
# Writes web/src/catalog/registry.gen.ts, the registry of every *.stories.tsx under web/src: one import per file, and
# storyModules keyed by each file's path relative to web/src. It also writes web/src/catalog/components.gen.ts: the
# component files under web/src, and the modules of each. The files are found with find and sorted in the C locale, so
# both are the same on every machine. web-check runs it first, and the catalog build runs it too.
set -euo pipefail

cd "$(dirname "$0")/.."
out=web/src/catalog/registry.gen.ts
tmp=$out.tmp

# The listing is a command substitution, not a process substitution: a failed cd or find makes this assignment fail, and
# set -e stops the script there, rather than writing a registry from a partial listing. pipefail carries find's status
# through the pipe.
listed=$(cd web/src && find . -name '*.stories.tsx' -type f | sed 's|^\./||' | LC_ALL=C sort)

files=()
if [ -n "$listed" ]; then
    while IFS= read -r rel; do
        files+=("$rel")
    done <<<"$listed"
fi

{
    echo "// Code generated by scripts/gen-stories.sh. DO NOT EDIT."
    for i in "${!files[@]}"; do
        printf 'import * as stories%d from "../%s";\n' "$i" "${files[$i]%.tsx}"
    done
    printf '\nexport const storyModules: Readonly<Record<string, Readonly<Record<string, unknown>>>> = {\n'
    for i in "${!files[@]}"; do
        printf '  "%s": stories%d,\n' "${files[$i]}" "$i"
    done
    printf '};\n'
} >"$tmp"
mv "$tmp" "$out"

# components.gen.ts lists every component file: each .tsx under web/src except the tests, the stories and the catalog's
# own files. It is listed the same way as the registry, so a failed find fails the script here too.
components_out=web/src/catalog/components.gen.ts
components_tmp=$components_out.tmp
listed_components=$(cd web/src && find . -name '*.tsx' -type f ! -name '*.test.tsx' ! -name '*.stories.tsx' \
    ! -path './catalog/*' | sed 's|^\./||' | LC_ALL=C sort)

components=()
if [ -n "$listed_components" ]; then
    while IFS= read -r rel; do
        components+=("$rel")
    done <<<"$listed_components"
fi

# componentModules imports each component file but main.tsx: importing main.tsx runs start, which mounts the page. The
# coverage check reads main.tsx's exemption from storyExemptions instead, so it needs no module of main.tsx.
imported=()
for rel in "${components[@]}"; do
    if [ "$rel" != "main.tsx" ]; then
        imported+=("$rel")
    fi
done

{
    echo "// Code generated by scripts/gen-stories.sh. DO NOT EDIT."
    for i in "${!imported[@]}"; do
        printf 'import * as components%d from "../%s";\n' "$i" "${imported[$i]%.tsx}"
    done
    printf '\nexport const componentFiles: readonly string[] = [\n'
    for rel in "${components[@]}"; do
        printf '  "%s",\n' "$rel"
    done
    printf '];\n'
    printf '\nexport const componentModules: Readonly<Record<string, Readonly<Record<string, unknown>>>> = {\n'
    for i in "${!imported[@]}"; do
        printf '  "%s": components%d,\n' "${imported[$i]}" "$i"
    done
    printf '};\n'
} >"$components_tmp"
mv "$components_tmp" "$components_out"
