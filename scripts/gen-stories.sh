#!/usr/bin/env bash
# Writes web/src/catalog/registry.gen.ts, the registry of every *.stories.tsx under web/src: one import per file, and
# storyModules keyed by each file's path relative to web/src. The files are found with find and sorted in the C locale,
# so the registry is the same on every machine. web-check runs it first, and the catalog build runs it too.
set -euo pipefail

cd "$(dirname "$0")/.."
out=web/src/catalog/registry.gen.ts
tmp=$out.tmp

# The listing is a command substitution, not a process substitution: a failed cd or find makes this assignment fail, and
# set -e stops the script there, rather than writing a registry from a partial listing. pipefail carries find's status
# through the pipe.
listed=$(cd web/src && find . -name '*.stories.tsx' -type f | sed 's|^\./||' | LC_ALL=C sort)

files=()
if [ -n "$listed" ]; then
    while IFS= read -r rel; do
        files+=("$rel")
    done <<<"$listed"
fi

{
    echo "// Code generated by scripts/gen-stories.sh. DO NOT EDIT."
    for i in "${!files[@]}"; do
        printf 'import * as stories%d from "../%s";\n' "$i" "${files[$i]%.tsx}"
    done
    printf '\nexport const storyModules: Readonly<Record<string, Readonly<Record<string, unknown>>>> = {\n'
    for i in "${!files[@]}"; do
        printf '  "%s": stories%d,\n' "${files[$i]}" "$i"
    done
    printf '};\n'
} >"$tmp"
mv "$tmp" "$out"
